[CreateAssetMenu(fileName = "Node", menuName = "WFC/Node")]
public class NodeData : ScriptableObject
{
    [System.Flags]
    public enum NodeType
    {
        Corner = 1<<0,
        Corridor = 1<<1,
        Deadend = 1<<2,
        Intersection = 1<<3,
        Junction = 1<<4,
        Staircase = 1<<5,
    };

    [System.Flags]
    public enum EnvironmentType
    {
        Objective = 1<<0,
        Study = 1<<1,
        Cellar = 1<<2,
        Garden = 1<<3,
    };
    
    public GameObject Prefab;
    public int Weight;
    public bool IsStairPiece;
    public bool CanHaveObjective = false;
    public bool IsDeadEnd = false;
    public NodeType nodeType;
    public EnvironmentType environmentType;
    [HideInInspector] public int ClockwiseRotationSteps; // Set automatically as the tile is rotated

    public NodeFaceVertical Up;
    public NodeFaceVertical Down;
    public NodeFaceHorizontal Left;
    public NodeFaceHorizontal Right;
    public NodeFaceHorizontal Front;
    public NodeFaceHorizontal Back;
    public List<Prop> validProps;

    public void SetRotation(float rotation)
    {
        if(Prefab != null)
            Prefab.transform.rotation = Quaternion.Euler(new Vector3(0, rotation, 0));
    }

    public Prop GetRandomPropCDF()
    {
        List<Prop> props = new List<Prop>(validProps);

        if(props.Count <= 0) return null;

        props.RemoveAll((p) => p.SpawnChance == 0.0f || 
            !p.CompareNode<NodeData.NodeType>(p.NodeTypeToSpawnIn, this.nodeType) || 
            !p.CompareNode<NodeData.EnvironmentType>(p.EnvironmentTypeToSpawnIn, this.environmentType));
        props.Sort((x, y) => x.SpawnChance.CompareTo(y.SpawnChance));

        int count = props.Count;

        if(count <= 0) return null;

        float totalProbability = 0;

        Prop[] cdf = new Prop[count];

        for (int i = 0; i < count; i++)
        {
            totalProbability += props[i].SpawnChance;

            Prop p = new Prop(props[i]);
            cdf[i] = p;
        }

        for (int i = 0; i < count; i++)
            cdf[i].SpawnChance /= totalProbability;

        float rand = UnityEngine.Random.value;

        int low = 0;
        int high = cdf.Length - 1;

        while (low < high)
        {
            int mid = (low + high) / 2;

            if (cdf[mid].SpawnChance >= rand)
                high = mid;
            else 
                low = mid + 1;
        }

        return cdf[low];
    }
}

